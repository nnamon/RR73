#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rows_hold_six_or_seven_bits_and_columns_three_checks() {
        let sevens = CHECK_TO_BITS.iter().filter(|r| r.len() == 7).count();
        assert!(CHECK_TO_BITS.iter().all(|r| r.len() == 6 || r.len() == 7));
        // 174 bits × 3 checks = 522 = 6 × 83 + 24.
        assert_eq!(sevens, 24);
        let mut column_weight = [0usize; N];
        for row in &CHECK_TO_BITS {
            for &b in row.iter() {
                column_weight[usize::from(b)] += 1;
            }
        }
        assert!(column_weight.iter().all(|&w| w == 3));
    }

    #[test]
    fn bit_to_checks_is_the_transpose_of_check_to_bits() {
        for (bit, checks) in BIT_TO_CHECKS.iter().enumerate() {
            for &c in checks {
                assert!(
                    CHECK_TO_BITS[usize::from(c)].contains(&(bit as u16)),
                    "bit {bit} check {c}"
                );
            }
            assert!(checks[0] < checks[1] && checks[1] < checks[2]);
        }
        for (c, row) in CHECK_TO_BITS.iter().enumerate() {
            for &b in row.iter() {
                assert!(BIT_TO_CHECKS[usize::from(b)].contains(&(c as u16)));
            }
        }
    }

    #[test]
    fn generator_rows_satisfy_every_check() {
        // Each unit message encodes to a codeword; all of them must satisfy the parity checks,
        // which proves the generator and the parity-check matrix describe the same code.
        for i in 0..K {
            let mut m = [0u8; 12];
            m[i / 8] = 0x80 >> (i % 8);
            assert_eq!(check(&encode(&m)), 0, "message bit {i}");
        }
    }

    #[test]
    fn check_counts_unsatisfied_rows() {
        let codeword = encode(&[0x5a; 12]);
        assert_eq!(check(&codeword), 0);
        for bit in [0usize, 90, 91, 173] {
            let mut bad = codeword;
            bad[bit] ^= 1;
            assert_eq!(check(&bad), 3, "bit {bit}");
        }
    }

    #[test]
    fn message_bits_inverts_encode() {
        let mut m = [0xc3u8; 12];
        m[11] &= 0xE0;
        assert_eq!(message_bits(&encode(&m)), m);
    }

    #[test]
    fn encode_ignores_bits_after_91() {
        let mut m = [0u8; 12];
        m[11] = 0x1F;
        assert_eq!(encode(&m), [0u8; N]);
    }
}
