//! FT8 and FT4 protocol primitives.
//!
//! This crate turns operator text into the 77-bit payload and back, adds the CRC-14,
//! encodes with the (174,91) LDPC code, maps codewords to tones and synthesises GFSK
//! audio. It contains no decoding logic; `rr73-decode` builds on the tables exported here.
//!
//! The transmit chain for one message:
//!
//! ```
//! use rr73_ft8::{message, synth, tones, CallsignHashes, Message, Mode};
//!
//! let mut hashes = CallsignHashes::new();
//! let msg = Message::parse("CQ K1ABC FN42").unwrap();
//! let payload = message::pack(&msg, &mut hashes).unwrap();
//! let symbols = tones::from_payload(Mode::Ft8, &payload);
//! let audio = synth::gfsk(Mode::Ft8, &symbols, 1500.0, 12_000, 1.0);
//! assert_eq!(audio.len(), 79 * 1920);
//! ```
//!
//! A receiver runs the chain backwards: LDPC decoding (in `rr73-decode`) yields a codeword,
//! [`ldpc::message_bits`] extracts the 91-bit message, [`crc::payload_from_message91`]
//! checks the CRC and undoes the FT4 scrambling, and [`message::unpack`] gives the message.
//!
//! References: Franke, Somerville and Taylor, "The FT4 and FT8 Communication Protocols",
//! QEX, July/August 2020 (cited below as "QEX"). Parts are ported from ft8_lib by Kārlis
//! Goba (MIT); each such file says so in its header, and ft8_lib's licence is in
//! `LICENSE-ft8_lib` next to this crate's manifest. Every function is checked against
//! ft8_lib with the vectors in `fixtures/ft8/`, generated by `tools/ft8lib/generate.sh`, and
//! the message codec against on-air transmissions in `fixtures/ft8/onair.json`.
//!
//! Units: frequencies in Hz, times in seconds, sample counts at 12 kHz unless stated.

pub mod crc;
pub mod hash;
pub mod ldpc;
pub mod message;
pub mod mode;
pub mod synth;
pub mod tones;

pub use hash::{CallHash, CallsignHashes, HashWidth};
pub use message::{Callsign, Message};
pub use mode::{Mode, ModeParams};

/// Number of payload bits in every FT8 and FT4 message.
pub const PAYLOAD_BITS: usize = 77;

/// A 77-bit message payload, most significant bit first. The last 3 bits of byte 9 are zero.
///
/// Functions that read a payload ignore those 3 bits; functions that build one leave them zero.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
pub struct Payload(pub [u8; 10]);

impl Payload {
    /// Returns bit `i` (0 = first transmitted bit) as 0 or 1. Bits past 79 read as 0.
    pub fn bit(&self, i: usize) -> u8 {
        self.0.get(i / 8).map_or(0, |byte| (byte >> (7 - (i % 8))) & 1)
    }

    /// Builds a payload from 77 bits given as 0/1 values, first transmitted bit first.
    pub fn from_bits(bits: &[u8]) -> Self {
        let mut out = [0u8; 10];
        for (i, &b) in bits.iter().take(PAYLOAD_BITS).enumerate() {
            out[i / 8] |= (b & 1) << (7 - (i % 8));
        }
        Payload(out)
    }

    /// Returns the message type field i3 (bits 74 to 76).
    pub fn i3(&self) -> u8 {
        (self.0[9] >> 3) & 0x07
    }

    /// Returns the subtype field n3 (bits 71 to 73). It is meaningful only when i3 is 0.
    pub fn n3(&self) -> u8 {
        ((self.0[8] & 0x01) << 2) | (self.0[9] >> 6)
    }

    /// Returns the payload with bits 77 to 79 cleared.
    pub fn masked(&self) -> Payload {
        let mut out = *self;
        out.0[9] &= 0xF8;
        out
    }

    /// Returns the payload XORed with [`tones::FT4_XOR`]. FT4 sends this scrambled payload
    /// (QEX, Appendix A); applying the function twice restores the original.
    pub fn ft4_scrambled(&self) -> Payload {
        let mut out = self.masked();
        for (byte, x) in out.0.iter_mut().zip(tones::FT4_XOR) {
            *byte ^= x;
        }
        out
    }
}
