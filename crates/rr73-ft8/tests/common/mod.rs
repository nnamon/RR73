//! Shared helpers for the integration tests: fixture loading, hex and a seeded generator.

#![allow(dead_code)]

use rr73_ft8::Payload;
use serde::Deserialize;
use std::path::PathBuf;

/// Path of a file in `fixtures/ft8/`.
pub fn fixture_path(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../fixtures/ft8")
        .join(name)
}

/// Reads and parses a JSON fixture.
pub fn load<T: for<'de> Deserialize<'de>>(name: &str) -> T {
    let path = fixture_path(name);
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("reading {}: {e}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("parsing {}: {e}", path.display()))
}

/// Decodes lowercase or uppercase hex.
pub fn hex(text: &str) -> Vec<u8> {
    assert!(text.len().is_multiple_of(2), "odd hex length: {text}");
    (0..text.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&text[i..i + 2], 16).unwrap_or_else(|_| panic!("bad hex: {text}")))
        .collect()
}

/// Encodes bytes as lowercase hex.
pub fn to_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// A payload from 20 hex digits.
pub fn payload(text: &str) -> Payload {
    let bytes = hex(text);
    let mut out = [0u8; 10];
    out.copy_from_slice(&bytes);
    Payload(out)
}

