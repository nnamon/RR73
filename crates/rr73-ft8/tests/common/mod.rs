/// A waveform generated by ft8_lib's GFSK modulator, sampled.
#[derive(Deserialize)]
pub struct Waveform {
    pub mode: String,
    pub text: String,
    pub f0_hz: f32,
    pub sample_rate: u32,
    pub tones: String,
    pub n_samples: usize,
    pub head_len: usize,
    pub stride: usize,
    pub head: Vec<f32>,
    pub tail: Vec<f32>,
    pub strided: Vec<f32>,
}

impl Waveform {
    /// Every stored sample with its index.
    pub fn samples(&self) -> Vec<(usize, f32)> {
        let mut out: Vec<(usize, f32)> = self.head.iter().copied().enumerate().collect();
        let tail_start = self.n_samples - self.head_len;
        out.extend(self.tail.iter().enumerate().map(|(i, &v)| (tail_start + i, v)));
        out.extend(
            self.strided
                .iter()
                .enumerate()
                .map(|(i, &v)| (i * self.stride, v)),
        );
        out
    }
}

/// Converts a string of tone digits.
pub fn tone_digits(text: &str) -> Vec<u8> {
    text.bytes().map(|b| b - b'0').collect()
}

/// SplitMix64: a small seeded generator, so property tests are reproducible.
pub struct Rng(u64);

impl Rng {
    pub fn new(seed: u64) -> Self {
        Rng(seed)
    }

    pub fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    /// Uniform in `0..n` (n > 0).
    pub fn below(&mut self, n: u64) -> u64 {
        self.next_u64() % n
    }

    pub fn coin(&mut self) -> bool {
        self.next_u64() & 1 == 1
    }

    pub fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        &items[self.below(items.len() as u64) as usize]
    }

    pub fn payload(&mut self) -> Payload {
        let mut bytes = [0u8; 10];
        for b in &mut bytes {
            *b = self.next_u64() as u8;
        }
        Payload(bytes).masked()
    }
}

/// Reads bits `from..to` of a payload as a number.
pub fn field(p: &Payload, from: usize, to: usize) -> u128 {
    (from..to).fold(0u128, |acc, i| (acc << 1) | u128::from(p.bit(i)))
}

/// Why a payload that unpacks is not in the form `pack` writes, or `None` if it is. Reads the
/// bits directly so it does not depend on the code under test, except for the hash itself.
pub fn noncanonical(p: &Payload) -> Option<&'static str> {
    const A38: &[u8] = b" 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ/";
    const A42: &[u8] = b" 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ+-./?";
    let digits = |mut v: u128, radix: u128, n: usize, alphabet: &[u8]| {
        let mut out = vec![b' '; n];
        for c in out.iter_mut().rev() {
            *c = alphabet[(v % radix) as usize];
            v /= radix;
        }
        String::from_utf8(out).unwrap_or_default()
    };
    match (p.i3(), p.n3()) {
        (0, 0) => {
            let text = digits(field(p, 0, 71), 42, 13, A42);
            text.ends_with(' ').then_some("free text not right-justified")
        }
        (1, _) | (2, _) => {
            let g15 = field(p, 59, 74);
            if g15 == 32_403 {
                Some("RR73 sent as g15 32403")
            } else if p.bit(58) == 1 && [32_401, 32_402, 32_404].contains(&g15) {
                Some("R before a blank, RRR or 73")
            } else if (32_506..=32_586).contains(&g15) {
                Some("report code 106 to 186")
            } else if p.i3() == 2 && p.bit(28) == 0 && p.bit(57) == 0 {
                Some("type 2 without /P")
            } else {
                None
            }
        }
        (4, _) => {
            let call = digits(field(p, 12, 70), 38, 11, A38);
            if call.ends_with(' ') {
                return Some("c58 not right-justified");
            }
            if p.bit(73) == 1 {
                let c = rr73_ft8::Callsign::new(call.trim()).ok()?;
                let h12 = rr73_ft8::CallHash::of(&c, rr73_ft8::HashWidth::Bits12).value();
                if field(p, 0, 12) != u128::from(h12) {
                    return Some("CQ h12 not the callsign's hash");
                }
            }
            None
        }
        _ => None,
    }
}
