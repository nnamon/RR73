#!/usr/bin/env node
// Builds web/public/icon.svg, the source for every app icon, from the RR73 mark in the plan: a
// slot-progress ring with a blue arc from 12 to 4 o'clock and the RR73 wordmark. The wordmark is
// set in IBM Plex Mono SemiBold (SIL Open Font Licence) and converted to outlines so the icon
// generator needs no fonts. Run in the node container:
//   docker compose run --rm node sh tools/icon/build.sh
// The background is the app's dark ground; the ring and arc echo the slot-progress ring on Operate.
import { writeFileSync, readFileSync } from 'node:fs';
import opentype from 'opentype.js';

const [fontPath, outPath] = process.argv.slice(2);
const font = opentype.parse(readFileSync(fontPath).buffer);

const S = 1024;
const C = {
  bg: '#0E1424',
  track: '#25304A',
  arc: '#5B86FF',
  ink: '#F2F4F8',
};

/** Path data for `text` centred on (cx, baseline) at `size` px, with letter spacing `track` em. */
function word(text, cx, baseline, size, trackEm = 0) {
  const glyphs = font.stringToGlyphs(text);
  const scale = size / font.unitsPerEm;
  const advances = glyphs.map((g) => g.advanceWidth * scale + trackEm * size);
  const width = advances.reduce((a, b) => a + b, 0) - trackEm * size;
  let x = cx - width / 2;
  let d = '';
  glyphs.forEach((g, i) => {
    d += g.getPath(x, baseline, size).toPathData(2);
    x += advances[i];
  });
  return d;
}

/** SVG arc path on a circle from angle a0 to a1 (degrees clockwise from 12 o'clock). */
function arc(cx, cy, r, a0, a1) {
  const p = (a) => [cx + r * Math.sin((a * Math.PI) / 180), cy - r * Math.cos((a * Math.PI) / 180)];
  const [x0, y0] = p(a0);
  const [x1, y1] = p(a1);
  return `M${x0.toFixed(2)} ${y0.toFixed(2)}A${r} ${r} 0 ${a1 - a0 > 180 ? 1 : 0} 1 ${x1.toFixed(2)} ${y1.toFixed(2)}`;
}

function ringText() {
  const cx = 512, cy = 512, r = 352, w = 60;
  // Cap height of Plex Mono is 0.698 em; centre the caps on the ring's centre.
  const size = 232;
  const baseline = cy + (0.698 * size) / 2;
  return [
    `<circle cx="${cx}" cy="${cy}" r="${r}" fill="none" stroke="${C.track}" stroke-width="${w}"/>`,
    `<path d="${arc(cx, cy, r, 0, 120)}" fill="none" stroke="${C.arc}" stroke-width="${w}" stroke-linecap="round"/>`,
    `<path d="${word('RR73', cx, baseline, size, -0.02)}" fill="${C.ink}"/>`,
  ].join('\n  ');
}

const body = ringText();
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}">
  <!-- Generated by tools/icon/build-icon.mjs. Wordmark: IBM Plex Mono SemiBold, SIL OFL 1.1. -->
  <rect width="${S}" height="${S}" fill="${C.bg}"/>
  ${body}
</svg>
`;
writeFileSync(outPath, svg);
console.log(`wrote ${outPath} (${svg.length} bytes)`);
